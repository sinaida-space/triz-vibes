export function getPrinciple(id: number): Principle {
  return (
    principles.find((principle) => principle.id === id) ?? {
      id,
      title: `Приём ${id}`,
      shortDefinition: "Дополнительный классический приём ТРИЗ, оставленный как расширение матрицы.",
      whenToUse: ["Когда компактная матрица ссылается на расширенный набор"],
      digitalArtApplication: "Используйте как повод вручную уточнить проектное действие.",
      aiWorkflowApplication: "Зафиксируйте связь приёма с противоречием перед генерацией.",
      miniExercise: "Сформулируйте одно действие по выбранному приёму."
    }
  );
}

export function buildPrincipleRecommendations(ids: number[], problem: string): PrincipleRecommendation[] {
  return ids.map((id) => {
    const principle = getPrinciple(id);
    return {
      principleId: principle.id,
      title: principle.title,
      reason: principle.shortDefinition,
      projectApplication: `${principle.digitalArtApplication} В контексте задачи: ${problem.slice(0, 120)}${problem.length > 120 ? "..." : ""}`,
      miniAction: principle.miniExercise
    };
  });
}
